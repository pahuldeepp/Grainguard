"""Private encrypted object storage for immutable original PDF versions."""

from __future__ import annotations

from dataclasses import dataclass
import re
from typing import Any
from urllib.parse import urlsplit
from uuid import uuid4



_BUCKET = re.compile(r"^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$")


@dataclass(frozen=True, slots=True)
class S3SourceConfig:
    bucket: str
    region: str
    kms_key_id: str
    endpoint_url: str | None = None


class S3PdfObjectStore:
    """Upload source PDFs with SSE-KMS and a server-generated immutable key."""

    def __init__(self, config: S3SourceConfig, *, client: Any | None = None):
        if not _BUCKET.fullmatch(config.bucket) or not config.region or not config.kms_key_id:
            raise ValueError("S3 bucket, region, and KMS key are required")
        if config.endpoint_url:
            parsed = urlsplit(config.endpoint_url)
            local_http = parsed.scheme == "http" and parsed.hostname in {"localhost", "127.0.0.1", "::1"}
            if (parsed.scheme != "https" and not local_http) or not parsed.hostname or parsed.username or parsed.password:
                raise ValueError("object-store endpoint must use HTTPS outside loopback")
        if client is None:
            import boto3

            client = boto3.client("s3", region_name=config.region, endpoint_url=config.endpoint_url)
        self._client = client
        self._config = config

    def put_pdf(self, pdf_bytes: bytes, *, tenant_id: str, document_id: str,
                document_version: int, source_sha256: str, source_object_key: str | None = None) -> str:
        key = (f"tenant/{tenant_id}/documents/{document_id}/"
               f"versions/{document_version}/objects/{uuid4()}/{source_sha256}.pdf")
        if source_object_key is not None:
            self._validate_key(source_object_key)
            prefix=f"tenant/{tenant_id}/documents/{document_id}/versions/{document_version}/objects/"
            if not source_object_key.startswith(prefix) or not source_object_key.endswith(f"/{source_sha256}.pdf"):
                raise ValueError("preallocated source key does not match upload")
            key=source_object_key
        params = {
            "Bucket": self._config.bucket,
            "Key": key,
            "Body": pdf_bytes,
            "ContentLength": len(pdf_bytes),
            "ContentType": "application/pdf",
            "Metadata": {
                "source-sha256": source_sha256,
                "document-version": str(document_version),
            },
            "ServerSideEncryption": "aws:kms",
            "SSEKMSKeyId": self._config.kms_key_id,
        }
        self._client.put_object(**params)
        return key

    def get_pdf(self, key: str) -> bytes:
        self._validate_key(key)
        response = self._client.get_object(Bucket=self._config.bucket, Key=key)
        body = response['Body']
        try:
            data = body.read(25 * 1024 * 1024 + 1)
            if len(data) > 25 * 1024 * 1024:
                raise ValueError('stored PDF exceeds ingestion size limit')
            return data
        finally:
            body.close()

    def delete_pdf(self, key: str) -> None:
        # Keys are only generated by put_pdf; reject arbitrary caller paths.
        self._validate_key(key)
        self._client.delete_object(Bucket=self._config.bucket, Key=key)

    @staticmethod
    def _validate_key(key: str) -> None:
        if not re.fullmatch(r"tenant/[0-9a-f-]{36}/documents/[0-9a-f-]{36}/versions/[1-9][0-9]*/objects/[0-9a-f-]{36}/[0-9a-f]{64}\.pdf", key):
            raise ValueError("source object key is invalid")
